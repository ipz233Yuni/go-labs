package main

import "fmt"

func main() {
	var x, y, z uint8

	x = 9  // 00001001 в двійковій формі
	y = 28 // 00011100 в двійковій формі
	z = x  // зберігаємо початкове значення x для подальших операцій

	fmt.Println("Бітові операції")

	fmt.Printf("^x      = ^(%d)      = ^(%.8b)            = %.8b = %d\n", x, x, ^x, ^x)
	// ^x — інверсія всіх бітів x (0 → 1, 1 → 0)
	// x = 00001001 → ^x = 11110110 = 246
	fmt.Printf("x << 2  = (%d << 2)  = (%.8b << 2)        = %.8b = %d\n", x, x, x<<2, x<<2)
	// x << 2: додає два нулі справа, зсуває біти вліво
	// 00001001 → 00100100 = 36
	fmt.Printf("x >> 2  = (%d >> 2)  = (%.8b >> 2)        = %.8b = %d\n", x, x, x>>2, x>>2)
	// x >> 2: відкидає два біти справа
	// 00001001 → 00000010 = 2
	fmt.Printf("x & y   = (%d & %d)  = (%.8b & %.8b)  = %.8b = %d\n", x, y, x, y, x&y, x&y)
	// 00001001 & 00011100 = 00001000 = 8
	fmt.Printf("x | y   = (%d | %d)  = (%.8b | %.8b)  = %.8b = %d\n", x, y, x, y, x|y, x|y)
	// 00001001 | 00011100 = 00011101 = 29
	fmt.Printf("x ^ y   = (%d ^ %d)  = (%.8b ^ %.8b)  = %.8b = %d\n", x, y, x, y, x^y, x^y)
	// 00001001 ^ 00011100 = 00010101 = 21
	fmt.Printf("x &^ y  = (%d &^ %d) = (%.8b &^ %.8b) = %.8b = %d\n", x, y, x, y, x&^y, x&^y)
	// Залишає біти x, де біти y = 0
	// 00001001 &^ 00011100 = 00000001 = 1
	fmt.Printf("x %% y   = (%d %% %d)  = (%.8b %% %.8b)  = %.8b = %d\n", x, y, x, y, x%y, x%y)
	// 9 % 28 = 9

	fmt.Println("\nБітові операції з присвоюванням")

	x = z // відновлюємо значення x
	x &= y
	fmt.Printf("x &= y   = (%d &= %d)  = (%.8b &= %.8b)  = %.8b = %d\n", z, y, z, y, x, x)
	// x = x & y = 8
	x = z
	x |= y
	fmt.Printf("x |= y   = (%d |= %d)  = (%.8b |= %.8b)  = %.8b = %d\n", z, y, z, y, x, x)
	// x = x | y = 29
	x = z
	x ^= y
	fmt.Printf("x ^= y   = (%d ^= %d)  = (%.8b ^= %.8b)  = %.8b = %d\n", z, y, z, y, x, x)
	// x = x ^ y = 21
	x = z
	x &^= y
	fmt.Printf("x &^= y  = (%d &^= %d) = (%.8b &^= %.8b) = %.8b = %d\n", z, y, z, y, x, x)
	// x = x &^ y = 1
	x = z
	x %= y
	fmt.Printf("x %%= y   = (%d %%= %d)  = (%.8b %%= %.8b)  = %.8b = %d\n", z, y, z, y, x, x)
	// x = x % y = 9

	// Завдання.
	// 1. Пояснити результати операцій
}
